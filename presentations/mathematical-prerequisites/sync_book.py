"""Keep the book's mathematical chapters generated from the guide sources."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
BOOK = ROOT.parents[1] / 'book'
PAGES = {
    1: '00-mathematical-foundations/language.qmd',
    2: '01-vector-calculus/operators.qmd',
    3: '01-vector-calculus/spherical.qmd',
    4: '02-harmonic-analysis/function-spaces.qmd',
    5: '03-pdes/eigenfunctions.qmd',
    6: '03-pdes/foundations.qmd',
    7: '02-harmonic-analysis/fourier-series.qmd',
    8: '02-harmonic-analysis/spherical-harmonics.qmd',
    9: '03-pdes/spectral-methods.qmd',
    11: '06-statistics/averages.qmd',
    12: '05-neural-operators/spectral-operators.qmd',
}
# The physical companion owns the book's fluid-dynamics sequence.
TARGETS = {**PAGES, 10: '04-geophysical-fluid-dynamics/barotropic.qmd'}
LABELS = {1: 'mathematical language', 2: 'calculus and conservation',
          3: 'spherical geometry', 4: 'function spaces', 5: 'eigenfunction theory',
          6: 'PDE foundations', 7: 'Fourier analysis', 8: 'spherical harmonics',
          9: 'spectral numerics', 10: 'barotropic dynamics',
          11: 'probability and averages', 12: 'integral and learned operators'}


def expected_pages():
    import os
    for source in sorted((ROOT / 'chapters').glob('*.md')):
        number = int(source.name[:2])
        if number not in PAGES:
            continue
        path = BOOK / PAGES[number]
        text = source.read_text()
        # Qualify equations independently of the book's own chapter ordering.
        text = re.sub(r'\\tag\{(\d+\.\d+)\}', r'\\tag{M\1}', text)
        text = re.sub(r'\((\d+\.\d+)\)', r'(M\1)', text)
        text = re.sub(r'\b(Definition|Assumption|Model|Law|Postulate|Result|Example|Counterexample|Remark|Exercise) (\d+\.\d+)\b', r'\1 M\2', text)
        # Turn guide chapter pointers into links to the owning book treatment.
        def link(match):
            n = int(match[1])
            if n not in TARGETS:
                return match[0]
            target = os.path.relpath(BOOK / TARGETS[n], path.parent)
            return f'[{LABELS[n]}]({target})'
        # Citation locators refer to their original publication, not the guide.
        pieces = re.split(r'(\[@[^\]]+\])', text)
        for i in range(0, len(pieces), 2):
            pieces[i] = re.sub(r'(?<!AW, )Chapter (\d+)\b', link, pieces[i])
        text = ''.join(pieces)
        text = text.replace('Section 8.4', '[the tangent-field decomposition](../02-harmonic-analysis/spherical-harmonics.qmd#zonal-means-tangent-vectors-and-isotropy)')
        text = text.replace('Answers appear in the separate self-test answer section.',
                            'Answers are in the mathematical companion document linked from the foundations reading map.')
        yield path, ('<!-- Generated by presentations/mathematical-prerequisites/sync_book.py; '
                     'edit chapters/*.md and run build.py --sync-book. -->\n\n' + text)


def sync(check=False):
    for path, expected in expected_pages():
        if check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'Book chapter out of sync: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
