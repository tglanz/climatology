#!/usr/bin/env python3
"""Build the PDF and synchronize general-theory book chapters from one manuscript."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = HERE / 'physical-prerequisites.md'
BOOK = ROOT / 'book'
CHAPTERS = {
    1: 'kinematics', 2: 'motion', 3: 'rotating', 4: 'vorticity', 5: 'layer-pv',
    6: 'barotropic', 7: 'turbulence', 8: 'inversion', 9: 'stochastic',
}
EVIDENCE = [
    'papers/atmospheric-and-oceanic-fluid-dymamics.pdf',
    'papers/barotropic.pdf',
    'papers/methods-of-mathemacial-for-physicists.pdf',
    'papers/vallis-etal-2024.pdf',
    'sim/barotropic_stirring.py',
    'submodules/isca/src/atmos_spectral_barotropic/barotropic_dynamics.F90',
    'submodules/isca/src/atmos_spectral_barotropic/stirring.F90',
    'submodules/isca/src/atmos_spectral/model/spectral_damping.F90',
]


def run(*args: str, cwd: Path = HERE) -> None:
    subprocess.run(args, cwd=cwd, check=True)


def chapters(text: str) -> dict[int, str]:
    matches = list(re.finditer(r'^# (.+)$', text, re.M))
    numbered = {}
    count = 0
    for i, match in enumerate(matches):
        if '.unnumbered' in match.group(1):
            continue
        count += 1
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        numbered[count] = text[match.start():end].strip() + '\n'
    return numbered


def sync_book(text: str, check: bool) -> None:
    sections = chapters(text)
    labels = r'(Definition|Assumption|Model|Law|Postulate|Result|Example|Counterexample|Remark|Exercise)'
    for number, name in CHAPTERS.items():
        body = sections[number]
        if number == 1:
            # Reuse the book's operator chapter, retaining parcel kinematics
            # and the vector identity that the momentum curl actually needs.
            first = body.split('## Gradient, divergence, curl, and Laplacian')[0]
            last = '## Material volumes and transport' + body.split('## Material volumes and transport', 1)[1]
            pattern = (r'^::: \{#obj-[^\n]+\}\n'
                       r'\*\*Result (\d+\.\d+) - Product and rotation identities\*\*.*?^:::')
            result = re.search(pattern, body, re.M | re.S)
            assert result is not None
            proof = re.search(r'^::: \{\.tb-proof\}\n\*\*Proof of Result '
                              + re.escape(result[1]) + r'\*\*.*?^:::', body, re.M | re.S)
            assert proof is not None
            bridge = ('## Vector identities used below\n\n'
                      'Product identities separate flux, advection, and rotation. '
                      'The book develops the general operators in '
                      '[vector calculus](../01-vector-calculus/operators.qmd) and '
                      '[integral theorems](../01-vector-calculus/theorems.qmd).\n\n')
            body = first + bridge + result[0] + '\n\n' + proof[0] + '\n\n' + last
            body = body.replace('in (1.2)', 'in the divergence definition')
            body = body.replace('are defined by (1.2)', 'are defined in the vector-calculus chapter')
        body = re.sub(r'[Cc]hapter (\d+)',
                      lambda m: f'[the companion chapter {m[1]}]({CHAPTERS[int(m[1])]}.qmd)'
                      if int(m[1]) in CHAPTERS else m[0], body)
        body = body.replace('the spatial gradient defined next', 'the spatial gradient introduced in vector calculus')
        body = re.sub(r'\\tag\{(\d+\.\d+)\}', r'\\tag{P\1}', body)
        body = re.sub(r'\(([1-9]\d*\.\d+)\)', r'(P\1)', body)
        body = re.sub(r'\b' + labels + r' (\d+\.\d+)', r'\1 P\2', body)
        intro = ('---\nformat:\n  html:\n    css: physical-textbook.css\n---\n\n'
                 '<!-- Generated by presentations/physical-prerequisites/build.py. '
                 'Edit its Markdown manuscript and run build.py --sync-book. -->\n\n')
        heading, rest = body.split('\n', 1)
        note = ('\n\nTeaching objects and equations prefixed **P** retain the companion '
                'physical-prerequisites numbering. Mathematical operators are introduced '
                'in [vector calculus](../01-vector-calculus/operators.qmd) and '
                '[integral theorems](../01-vector-calculus/theorems.qmd). '
                'Parcel derivatives and transport are developed in [fluid kinematics](kinematics.qmd).\n')
        expected = intro + heading + note + rest
        path = BOOK / '04-geophysical-fluid-dynamics' / f'{name}.qmd'
        if check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'Book chapter is out of sync: {path}')
        else:
            path.write_text(expected)
    css = HERE / 'textbook.css'
    book_css = BOOK / '04-geophysical-fluid-dynamics' / 'physical-textbook.css'
    if check:
        if not book_css.exists() or book_css.read_text() != css.read_text():
            raise SystemExit('Book teaching-object styles are out of sync')
    else:
        book_css.write_text(css.read_text())


def lint(text: str) -> None:
    tags = re.findall(r'\\tag\{([^}]+)\}', text)
    anchors = re.findall(r'\[\]\{#([^}]+)\}', text)
    if len(tags) != len(set(tags)) or len(anchors) != len(set(anchors)):
        raise SystemExit('Duplicate equation tag or anchor')
    if len(tags) != 49 or text.count('$$') % 2:
        raise SystemExit('Expected 49 milestone equations and paired math delimiters')
    sections = chapters(text)
    if len(sections) != 10:
        raise SystemExit('Expected ten substantive chapters')
    object_pattern = (r'^\*\*(Definition|Assumption|Model|Law|Postulate|Result|Example|'
                      r'Counterexample|Remark) (\d+)\.(\d+) - (.+)\*\*$')
    objects = re.findall(object_pattern, text, re.M)
    for i, body in sections.items():
        if '## Chapter summary' not in body or '## Exercises' not in body:
            raise SystemExit(f'Missing recap or exercises in chapter {i}')
        opening = body.split('\n\n', 2)[1]
        if '?' not in opening:
            raise SystemExit(f'Missing chapter question in chapter {i}')
        local = [int(n) for _, ch, n, _ in objects if int(ch) == i]
        if local != list(range(1, len(local) + 1)):
            raise SystemExit(f'Nonconsecutive teaching-object numbering in chapter {i}')
        if not re.search(r'^\*\*Example ' + str(i) + r'\.', body, re.M):
            raise SystemExit(f'Missing worked example in chapter {i}')
        exercises = re.findall(r'^\*\*Exercise ' + str(i) + r'\.(\d+) - ', body, re.M)
        if exercises != ['1', '2', '3']:
            raise SystemExit(f'Expected three numbered exercises in chapter {i}')
    targets = {f'{kind} {ch}.{n}' for kind, ch, n, _ in objects}
    for target in re.findall(r'^\*\*(?:Proof|Derivation) of ([^*]+)\*\*$', text, re.M):
        if target not in targets:
            raise SystemExit(f'Missing argument target: {target}')
    answers = (HERE / 'instructor-solutions.md').read_text()
    if len(re.findall(r'^## Solution to Exercise ', answers, re.M)) != 30:
        raise SystemExit('Expected thirty separate instructor solutions')
    if re.search(r'^## (Answers|Derivation checks)', text, re.M):
        raise SystemExit('Student manuscript must not include the instructor answer key')
    if any(ord(char) > 127 for char in text + answers):
        raise SystemExit('Use ASCII prose and LaTeX')
    print(f'Checked ten chapters, {len(objects)} teaching objects, thirty exercises, and {len(tags)} equations.')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sync-book', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = SOURCE.read_text()
    lint(text)
    sync_book(text, check=args.check)
    if args.check or args.sync_book:
        return
    if not shutil.which('pandoc') or not shutil.which('xelatex'):
        raise SystemExit('Install Pandoc and XeLaTeX before building.')
    with tempfile.TemporaryDirectory(prefix='physical-prerequisites-') as temp:
        tempdir = Path(temp)
        tex = tempdir / 'physical-prerequisites.tex'
        run('pandoc', str(SOURCE), '--standalone', '--citeproc',
            '--bibliography', str(BOOK / 'references.bib'),
            '--top-level-division=chapter', '--number-sections', '--toc', '--toc-depth=2',
            '--lua-filter', str(HERE / 'headers.lua'),
            '--lua-filter', str(HERE / 'objects.lua'),
            '--include-in-header', str(HERE / 'header.tex'),
            '-V', 'documentclass=report', '-V', 'classoption=oneside',
            '-V', 'fontsize=11pt', '-V', 'papersize=a4',
            '-V', 'geometry:margin=25mm', '-V', 'geometry:top=31mm',
            '-V', 'colorlinks=true',
            '-o', str(tex))
        for _ in range(3):
            run('xelatex', '-interaction=nonstopmode', '-halt-on-error',
                '-output-directory', str(tempdir), str(tex))
        log = tex.with_suffix('.log').read_text(errors='replace')
        (HERE / 'build.log').write_text(log)
        if re.search(r'Overfull \\[hv]box|Missing character:', log):
            raise SystemExit('Layout/glyph problem; inspect build.log before delivering.')
        shutil.copy2(tex.with_suffix('.pdf'), HERE / 'physical-prerequisites.pdf')
    evidence = {}
    for name in EVIDENCE:
        path = ROOT / name
        evidence[name] = hashlib.sha256(path.read_bytes()).hexdigest()
    record = {
        'manuscript_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'evidence_sha256': evidence,
        'repository_revision_at_build': subprocess.check_output(
            ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'isca_revision': subprocess.check_output(
            ['git', '-C', str(ROOT / 'submodules/isca'), 'rev-parse', 'HEAD'], text=True).strip(),
        'isca_worktree_status': subprocess.check_output(
            ['git', '-C', str(ROOT / 'submodules/isca'), 'status', '--short'], text=True),
        'pandoc': subprocess.check_output(['pandoc', '--version'], text=True).splitlines()[0],
        'engine': 'XeLaTeX, three passes; header.tex; report, A4, 11pt',
        'equation_numbering': 'Preserved 49 chapter-equation tags; book uses P prefix',
        'rendering_sha256': {name: hashlib.sha256((HERE / name).read_bytes()).hexdigest() for name in ['build.py', 'header.tex', 'headers.lua', 'objects.lua', 'textbook.css']},
        'editorial_style': 'tg-make-textbook; physics primary, mathematical support; graduate audience',
        'teaching_objects': len(re.findall(r'^\*\*(?:Definition|Assumption|Model|Law|Postulate|Result|Example|Counterexample|Remark) \d+\.\d+ - ', text, re.M)),
        'exercises': 30,
        'instructor_solutions_sha256': hashlib.sha256((HERE / 'instructor-solutions.md').read_bytes()).hexdigest(),
    }
    (HERE / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    print(HERE / 'physical-prerequisites.pdf')


if __name__ == '__main__':
    main()
