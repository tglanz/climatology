#!/usr/bin/env python3
"""Build the PDF and synchronize general-theory book chapters from one manuscript."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = HERE / 'physical-prerequisites.md'
BOOK = ROOT / 'book'
CHAPTERS = {
    1: 'kinematics', 2: 'motion', 3: 'rotating', 4: 'vorticity', 5: 'layer-pv',
    6: 'barotropic', 7: 'turbulence', 8: 'inversion', 9: 'stochastic',
}
EVIDENCE = [
    'papers/atmospheric-and-oceanic-fluid-dymamics.pdf',
    'papers/barotropic.pdf',
    'papers/methods-of-mathemacial-for-physicists.pdf',
    'papers/vallis-etal-2024.pdf',
    'sim/barotropic_stirring.py',
    'submodules/isca/src/atmos_spectral_barotropic/barotropic_dynamics.F90',
    'submodules/isca/src/atmos_spectral_barotropic/stirring.F90',
    'submodules/isca/src/atmos_spectral/model/spectral_damping.F90',
]


def run(*args: str, cwd: Path = HERE) -> None:
    subprocess.run(args, cwd=cwd, check=True)


def chapters(text: str) -> dict[int, str]:
    matches = list(re.finditer(r'^# (.+)$', text, re.M))
    numbered = {}
    count = 0
    for i, match in enumerate(matches):
        if '.unnumbered' in match.group(1):
            continue
        count += 1
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        numbered[count] = text[match.start():end].strip() + '\n'
    return numbered


def sync_book(text: str, check: bool) -> None:
    sections = chapters(text)
    for number, name in CHAPTERS.items():
        # The book has its own chapter sequence. Prefixing equation tags avoids
        # implying that source chapter numbers are the book's chapter numbers.
        body = sections[number]
        if number == 1:
            # Keep parcel kinematics here; the book already owns the general
            # differential operators and integral theorems in vector calculus.
            first = body.split('## Gradient, divergence, curl, and Laplacian')[0]
            last = '## Material volumes and transport' + body.split('## Material volumes and transport', 1)[1]
            identity = re.search(r'\[\]\{#law-identities\}.*?\$\$.*?\$\$', body, re.S).group(0)
            bridge = ('## Vector identities used below\n\n'
                      '**Result and motivation.** Product identities separate flux, '
                      'advection, and rotation in the conservation equations. '
                      'Differential operators and integral theorems are defined in '
                      '[vector calculus](../01-vector-calculus/operators.qmd) and '
                      '[its integral theorems](../01-vector-calculus/theorems.qmd). '
                      'For a scalar $b$ and vectors $\\mathbf{a},\\mathbf{v}$, '
                      'componentwise expansion gives [@ArfkenWeber2005, sec. 1.9]\n\n')
            body = first + bridge + identity + '\n\n' + last
            body = body.replace('in (1.2)', 'in the divergence definition')
            body = body.replace('are defined by (1.2)', 'are defined in the vector-calculus chapter')
        body = re.sub(r'[Cc]hapter ([1-9])', lambda match: f'[the companion chapter {match[1]}]({CHAPTERS[int(match[1])]}.qmd)', body)
        body = body.replace('the spatial gradient defined next', 'the spatial gradient introduced in vector calculus')
        body = re.sub(r'\\tag\{(\d+\.\d+)\}', r'\\tag{P\1}', body)
        # Prose uses explicit source equation numbers; qualify parenthesized
        # references and equation ranges without changing bibliographic locators.
        body = re.sub(r'\(([1-9]\.\d+)\)', r'(P\1)', body)
        intro = ('<!-- Generated by presentations/physical-prerequisites/build.py. '
                 'Edit its Markdown manuscript and run build.py --sync-book. -->\n\n')
        heading, rest = body.split('\n', 1)
        note = ('\n\nEquations prefixed **P** retain the numbering of the companion '
                'physical-prerequisites document. Mathematical operators are introduced '
                'in [vector calculus](../01-vector-calculus/operators.qmd) and '
                '[integral theorems](../01-vector-calculus/theorems.qmd). '
                'Parcel derivatives and transport are developed in [fluid kinematics](kinematics.qmd).\n')
        expected = intro + heading + note + rest
        path = BOOK / '04-geophysical-fluid-dynamics' / f'{name}.qmd'
        if check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'Book chapter is out of sync: {path}')
        else:
            path.write_text(expected)


def lint(text: str) -> None:
    tags = re.findall(r'\\tag\{([^}]+)\}', text)
    anchors = re.findall(r'\[\]\{#([^}]+)\}', text)
    if len(tags) != len(set(tags)) or len(anchors) != len(set(anchors)):
        raise SystemExit('Duplicate equation tag or anchor')
    if text.count('$$') % 2:
        raise SystemExit('Unpaired display-math delimiter')
    if len(chapters(text)) != 10:
        raise SystemExit('Expected ten substantive chapters')
    for i, body in chapters(text).items():
        if '## Chapter summary' not in body:
            raise SystemExit(f'Missing summary in chapter {i}')
        for heading, content in re.findall(r'^## ([^\n]+)\n(.*?)(?=^## |\Z)', body, re.M | re.S):
            if heading != 'Chapter summary' and not content.lstrip().startswith('**Result and motivation.**'):
                raise SystemExit(f'Missing result-first opening: {heading}')
    if any(ord(char) > 127 for char in text):
        raise SystemExit('Manuscript must use ASCII prose and LaTeX')
    print(f'Checked {len(chapters(text))} chapters, {len(tags)} numbered equations, {len(anchors)} equation anchors.')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sync-book', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = SOURCE.read_text()
    lint(text)
    sync_book(text, check=args.check)
    if args.check or args.sync_book:
        return
    if not shutil.which('pandoc') or not shutil.which('xelatex'):
        raise SystemExit('Install Pandoc and XeLaTeX before building.')
    with tempfile.TemporaryDirectory(prefix='physical-prerequisites-') as temp:
        tempdir = Path(temp)
        tex = tempdir / 'physical-prerequisites.tex'
        run('pandoc', str(SOURCE), '--standalone', '--citeproc',
            '--bibliography', str(BOOK / 'references.bib'),
            '--top-level-division=chapter', '--number-sections', '--toc', '--toc-depth=2',
            '--lua-filter', str(HERE / 'headers.lua'),
            '--include-in-header', str(HERE / 'header.tex'),
            '-V', 'documentclass=report', '-V', 'classoption=oneside',
            '-V', 'fontsize=11pt', '-V', 'papersize=a4',
            '-V', 'geometry:margin=25mm', '-V', 'geometry:top=31mm',
            '-V', 'colorlinks=true',
            '-o', str(tex))
        for _ in range(3):
            run('xelatex', '-interaction=nonstopmode', '-halt-on-error',
                '-output-directory', str(tempdir), str(tex))
        log = tex.with_suffix('.log').read_text(errors='replace')
        (HERE / 'build.log').write_text(log)
        if re.search(r'Overfull \\[hv]box|Missing character:', log):
            raise SystemExit('Layout/glyph problem; inspect build.log before delivering.')
        shutil.copy2(tex.with_suffix('.pdf'), HERE / 'physical-prerequisites.pdf')
    evidence = {}
    for name in EVIDENCE:
        path = ROOT / name
        evidence[name] = hashlib.sha256(path.read_bytes()).hexdigest()
    record = {
        'manuscript_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        'evidence_sha256': evidence,
        'repository_revision_at_build': subprocess.check_output(
            ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'isca_revision': subprocess.check_output(
            ['git', '-C', str(ROOT / 'submodules/isca'), 'rev-parse', 'HEAD'], text=True).strip(),
        'isca_worktree_status': subprocess.check_output(
            ['git', '-C', str(ROOT / 'submodules/isca'), 'status', '--short'], text=True),
        'pandoc': subprocess.check_output(['pandoc', '--version'], text=True).splitlines()[0],
        'engine': 'XeLaTeX, three passes; header.tex; report, A4, 11pt',
        'equation_numbering': 'Explicit chapter-equation tags; book uses P prefix',
    }
    (HERE / 'build-record.json').write_text(json.dumps(record, indent=2) + '\n')
    print(HERE / 'physical-prerequisites.pdf')


if __name__ == '__main__':
    main()
